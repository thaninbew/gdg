"""
Headline metrics on the holdout (data/test.parquet). Labels are read ONLY to score predictions;
every system call sees subject + body only.

    uv run python -m eval.metrics          # all metrics (20 end-to-end tickets call Gemma)
    uv run python -m eval.metrics --no-e2e # skip the Gemma part

Writes eval/results/metrics.json and eval/results/METRICS.md.
"""
import json
import statistics
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import f1_score

from triage.classifier import DATA, HP_THRESHOLD, PRIORITY_MAP, _load, predict_priority, ticket_text

OUT = Path(__file__).resolve().parent / "results"
RETRIEVAL_N, E2E_N, SEED = 500, 20, 0


def triage_metrics(test):
    models = _load()
    X = [ticket_text(s, b) for s, b in zip(test["subject"], test["body"])]
    t0 = time.perf_counter()
    probs = {t: models[t].predict_proba(X) for t in models}
    ms_per_ticket = (time.perf_counter() - t0) * 1000 / len(X)

    out = {"n_test": len(test), "triage_ms_per_ticket_batched": round(ms_per_ticket, 3)}
    preds = {}
    for t in ("type", "queue"):
        preds[t] = models[t].classes_[probs[t].argmax(1)]
    pc = models["priority"].classes_
    preds["priority"] = np.array([predict_priority(p, pc, HP_THRESHOLD)[0] for p in probs["priority"]])

    y = {"type": test["type"], "queue": test["queue"], "priority": test["priority"].map(PRIORITY_MAP)}
    for t in ("type", "queue", "priority"):
        mask = y[t].notna().values  # rows without a label are not scored (same as training)
        out[f"{t}_macro_f1"] = round(f1_score(y[t][mask].astype(str), preds[t][mask], average="macro"), 4)
        out[f"{t}_n_scored"] = int(mask.sum())

    hp_inc = ((y["priority"] == "high") & (test["type"] == "Incident")).values
    out["hp_incident_n"] = int(hp_inc.sum())
    # what the threshold was tuned for: true high/critical Incidents predicted priority "high"
    out["hp_incident_recall"] = round(float((preds["priority"][hp_inc] == "high").mean()), 4)
    # stricter: also predicted as an Incident, i.e. the gate's "page the on-call" rule fires
    out["hp_incident_recall_pred_high_and_incident"] = round(
        float(((preds["priority"] == "high") & (preds["type"] == "Incident"))[hp_inc].mean()), 4)
    out["share_flagged_high"] = round(float((preds["priority"] == "high").mean()), 4)
    out["hp_threshold"] = HP_THRESHOLD
    return out


def retrieval_metrics(test):
    from retrieval.retriever import retrieve
    sample = test[test["queue"].notna()].sample(RETRIEVAL_N, random_state=SEED)
    hits, top1, ms = 0, 0, []
    for s, b, q in zip(sample["subject"], sample["body"], sample["queue"]):
        t0 = time.perf_counter()
        precs = retrieve(s, b, k=5)
        ms.append((time.perf_counter() - t0) * 1000)
        queues = [p.queue for p in precs]
        hits += str(q) in queues
        top1 += bool(queues) and queues[0] == str(q)
    return {"retrieval_n": RETRIEVAL_N, "retrieval_same_queue_in_top5": round(hits / RETRIEVAL_N, 4),
            "retrieval_same_queue_top1": round(top1 / RETRIEVAL_N, 4),
            "retrieval_ms_median": round(statistics.median(ms), 1)}


def e2e_metrics(test):
    import pipeline
    sample = test.sample(E2E_N, random_state=SEED + 1)
    pipeline.run(sample["subject"].iloc[0], sample["body"].iloc[0])  # warm-up (model loading), not timed
    lat, grounded, escalated, sources = [], 0, 0, set()
    for s, b in zip(sample["subject"], sample["body"]):
        t0 = time.perf_counter()
        r = pipeline.run(s, b)
        lat.append((time.perf_counter() - t0) * 1000)
        grounded += bool(r["draft"]["grounded"])
        escalated += bool(r["escalate"])
        sources |= {f"{k}:{v}" for k, v in r["sources"].items()}
    lat_sorted = sorted(lat)
    return {"e2e_n": E2E_N, "e2e_latency_ms_mean": round(statistics.mean(lat), 1),
            "e2e_latency_ms_median": round(statistics.median(lat), 1),
            "e2e_latency_ms_p95": round(lat_sorted[min(len(lat) - 1, int(0.95 * len(lat)))], 1),
            "e2e_latency_ms_max": round(max(lat), 1),
            "e2e_grounded_share": round(grounded / E2E_N, 4),
            "e2e_escalated_share": round(escalated / E2E_N, 4),
            "e2e_stage_sources": sorted(sources)}


def write_md(m):
    lines = ["# Holdout metrics", "",
             f"Generated by `uv run python -m eval.metrics` on `data/test.parquet` ({m['n_test']} tickets). "
             "Labels are used only for scoring.", "",
             "## Triage", "",
             "| Metric | Value |", "|---|---|",
             f"| Type macro-F1 | {m['type_macro_f1']:.3f} (n={m['type_n_scored']}) |",
             f"| Queue macro-F1 | {m['queue_macro_f1']:.3f} (n={m['queue_n_scored']}) |",
             f"| Priority macro-F1 (3 levels, P(high) >= {m['hp_threshold']}) | {m['priority_macro_f1']:.3f} |",
             f"| High-priority Incident recall (predicted high) | {m['hp_incident_recall']:.1%} "
             f"(n={m['hp_incident_n']}) |",
             f"| ...and also predicted as Incident (on-call page fires) | "
             f"{m['hp_incident_recall_pred_high_and_incident']:.1%} |",
             f"| Share of tickets flagged high | {m['share_flagged_high']:.1%} |",
             f"| Triage latency (batched) | {m['triage_ms_per_ticket_batched']:.2f} ms/ticket |", "",
             "Priority uses 3 levels: critical+high = high, medium, low+very_low = low.", "",
             "## Retrieval", "",
             f"Share of {m['retrieval_n']} random test tickets whose top 5 includes a past ticket from the same "
             f"queue: **{m['retrieval_same_queue_in_top5']:.1%}** (top-1: {m['retrieval_same_queue_top1']:.1%}; "
             f"median {m['retrieval_ms_median']:.0f} ms per query).", ""]
    if "e2e_n" in m:
        lines += ["## End to end (`pipeline.run`)", "",
                  f"{m['e2e_n']} random test tickets, after one warm-up call.", "",
                  "| Metric | Value |", "|---|---|",
                  f"| Latency mean / median | {m['e2e_latency_ms_mean'] / 1000:.1f} s / "
                  f"{m['e2e_latency_ms_median'] / 1000:.1f} s |",
                  f"| Latency p95 / max | {m['e2e_latency_ms_p95'] / 1000:.1f} s / "
                  f"{m['e2e_latency_ms_max'] / 1000:.1f} s |",
                  f"| Grounded drafts | {m['e2e_grounded_share']:.0%} |",
                  f"| Escalated | {m['e2e_escalated_share']:.0%} |", "",
                  f"Stages: {', '.join(m['e2e_stage_sources'])}.", ""]
    (OUT / "METRICS.md").write_text("\n".join(lines))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    test = pd.read_parquet(DATA / "test.parquet")
    m = triage_metrics(test)
    m |= retrieval_metrics(test)
    if "--no-e2e" not in sys.argv:
        m |= e2e_metrics(test)
    (OUT / "metrics.json").write_text(json.dumps(m, indent=1))
    write_md(m)
    print(json.dumps(m, indent=1))


if __name__ == "__main__":
    main()
